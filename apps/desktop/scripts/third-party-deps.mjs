#!/usr/bin/env node
// Rewrites the dependency list at the end of THIRD_PARTY_NOTICES.md from Cargo.lock (via
// `cargo metadata`) and the npm packages the app ships. Run after changing dependencies.
import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const marker = "<!-- dependency list: generated by scripts/third-party-deps.mjs -->";
const noticesPath = join(root, "THIRD_PARTY_NOTICES.md");

const metadata = JSON.parse(
  execFileSync("cargo", ["metadata", "--format-version", "1", "--locked"], { cwd: join(root, "src-tauri"), maxBuffer: 64 << 20 }),
);
const ours = new Set(metadata.workspace_members);
const crates = metadata.packages
  .filter((p) => !ours.has(p.id))
  .map((p) => `| ${p.name} | ${p.version} | ${p.license ?? "see crate"} |`)
  .sort();

// npm packages bundled into the web view (runtime dependencies only).
const lock = JSON.parse(readFileSync(join(root, "..", "..", "package-lock.json"), "utf8")).packages;
const seen = new Set();
const npm = [];
const visit = (name) => {
  if (seen.has(name)) return;
  seen.add(name);
  const entry = lock[`apps/desktop/node_modules/${name}`] ?? lock[`node_modules/${name}`];
  if (!entry || entry.link) return; // workspace packages are ours
  npm.push(`| ${name} | ${entry.version} | ${entry.license ?? "see package"} |`);
  Object.keys(entry.dependencies ?? {}).forEach(visit);
};
Object.keys(lock["apps/desktop"].dependencies).forEach(visit);

const notices = readFileSync(noticesPath, "utf8").split(marker)[0].trimEnd();
writeFileSync(
  noticesPath,
  `${notices}\n\n${marker}\n\n### npm packages in the app window\n\n| Package | Version | License |\n|---|---|---|\n${npm.sort().join("\n")}\n\n` +
    `### Rust crates (all platforms in Cargo.lock)\n\n| Crate | Version | License |\n|---|---|---|\n${crates.join("\n")}\n`,
);
console.log(`${npm.length} npm packages, ${crates.length} crates`);
